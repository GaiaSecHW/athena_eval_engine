"""Evaluation 状态机（§10.2 / §10.18 白名单）。

非白名单 transition → INVALID_TRANSITION 拒绝。
"""
from __future__ import annotations

RUNNING_STATES = {
    "VALIDATING", "INGESTING", "PARSING", "RESOLVING", "PAIRING",
    "CALCULATING", "STATISTICAL_ANALYSIS", "DIAGNOSING", "REPORTING", "FINALIZING",
}
TERMINAL = {"COMPLETED", "COMPLETED_WITH_WARNINGS", "FAILED", "CANCELLED"}

WHITELIST = {
    ("CREATED", "VALIDATING"),
    ("VALIDATING", "INGESTING"), ("VALIDATING", "FAILED"),
    ("INGESTING", "PARSING"), ("INGESTING", "FAILED"),
    ("PARSING", "RESOLVING"), ("PARSING", "FAILED"),
    ("RESOLVING", "PAIRING"), ("RESOLVING", "FAILED"),
    ("PAIRING", "CALCULATING"), ("PAIRING", "FAILED"),
    ("CALCULATING", "STATISTICAL_ANALYSIS"), ("CALCULATING", "FAILED"),
    ("STATISTICAL_ANALYSIS", "DIAGNOSING"), ("STATISTICAL_ANALYSIS", "FAILED"),
    ("DIAGNOSING", "REPORTING"), ("DIAGNOSING", "FAILED"),
    ("REPORTING", "FINALIZING"), ("REPORTING", "FAILED"),
    ("FINALIZING", "COMPLETED"), ("FINALIZING", "COMPLETED_WITH_WARNINGS"), ("FINALIZING", "FAILED"),
    ("CANCEL_REQUESTED", "CANCELLING"),
}
# RUNNING → CANCEL_REQUESTED / CANCELLING
for s in RUNNING_STATES:
    WHITELIST.add((s, "CANCEL_REQUESTED"))
    WHITELIST.add((s, "CANCELLING"))
WHITELIST.add(("CANCELLING", "CANCELLED"))
for s in ("FAILED", "CANCELLED"):
    WHITELIST.add((s, "VALIDATING"))  # resume


def can_transition(frm: str, to: str) -> bool:
    return (frm, to) in WHITELIST


def assert_transition(frm: str, to: str):
    if not can_transition(frm, to):
        raise ValueError(f"INVALID_TRANSITION: {frm} -> {to}（不在白名单）")


PIPELINE = [
    "CREATED", "VALIDATING", "INGESTING", "PARSING", "RESOLVING", "PAIRING",
    "CALCULATING", "STATISTICAL_ANALYSIS", "DIAGNOSING", "REPORTING", "FINALIZING",
]
